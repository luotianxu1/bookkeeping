-- 定期存款：本金为内部转移，实际利息为收入，预计利息不计入资产。
USE bookkeeping_app;
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS term_deposits (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  account_id BIGINT UNSIGNED NOT NULL,
  funding_account_id BIGINT UNSIGNED NULL,
  payout_account_id BIGINT UNSIGNED NOT NULL,
  parent_deposit_id BIGINT UNSIGNED NULL,
  name VARCHAR(80) NOT NULL,
  currency_code CHAR(3) NOT NULL,
  principal DECIMAL(18,2) NOT NULL,
  annual_rate DECIMAL(8,4) NOT NULL,
  start_date DATE NOT NULL,
  maturity_date DATE NOT NULL,
  term_months INT NULL,
  maturity_action VARCHAR(24) NOT NULL DEFAULT 'withdraw',
  opening_mode VARCHAR(20) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'active',
  remark VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  KEY idx_term_deposit_due (user_id, status, maturity_date),
  KEY idx_term_deposit_account (account_id, status),
  CONSTRAINT fk_term_deposit_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_term_deposit_account FOREIGN KEY (account_id) REFERENCES accounts(id),
  CONSTRAINT fk_term_deposit_funding FOREIGN KEY (funding_account_id) REFERENCES accounts(id),
  CONSTRAINT fk_term_deposit_payout FOREIGN KEY (payout_account_id) REFERENCES accounts(id),
  CONSTRAINT fk_term_deposit_parent FOREIGN KEY (parent_deposit_id) REFERENCES term_deposits(id),
  CONSTRAINT chk_term_deposit_principal CHECK (principal > 0),
  CONSTRAINT chk_term_deposit_rate CHECK (annual_rate BETWEEN 0 AND 100),
  CONSTRAINT chk_term_deposit_dates CHECK (maturity_date > start_date),
  CONSTRAINT chk_term_deposit_status CHECK (status IN ('active','closed','voided'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='定期存单';

CREATE TABLE IF NOT EXISTS term_deposit_operations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  deposit_id BIGINT UNSIGNED NOT NULL,
  operation VARCHAR(24) NOT NULL,
  cash_account_id BIGINT UNSIGNED NULL,
  child_deposit_id BIGINT UNSIGNED NULL,
  principal_transaction_id BIGINT UNSIGNED NULL,
  interest_transaction_id BIGINT UNSIGNED NULL,
  renewal_transaction_id BIGINT UNSIGNED NULL,
  principal DECIMAL(18,2) NOT NULL DEFAULT 0,
  interest DECIMAL(18,2) NOT NULL DEFAULT 0,
  cash_delta DECIMAL(18,2) NOT NULL DEFAULT 0,
  occurred_on DATE NOT NULL,
  detail VARCHAR(2000) NULL,
  reversed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  KEY idx_term_operation_history (deposit_id, id),
  CONSTRAINT fk_term_operation_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_term_operation_deposit FOREIGN KEY (deposit_id) REFERENCES term_deposits(id),
  CONSTRAINT fk_term_operation_cash FOREIGN KEY (cash_account_id) REFERENCES accounts(id),
  CONSTRAINT fk_term_operation_child FOREIGN KEY (child_deposit_id) REFERENCES term_deposits(id),
  CONSTRAINT fk_term_operation_principal FOREIGN KEY (principal_transaction_id) REFERENCES transactions(id),
  CONSTRAINT fk_term_operation_interest FOREIGN KEY (interest_transaction_id) REFERENCES transactions(id),
  CONSTRAINT fk_term_operation_renewal FOREIGN KEY (renewal_transaction_id) REFERENCES transactions(id),
  CONSTRAINT chk_term_operation_interest CHECK (interest >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='定期存单操作与结算记录';
