import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

const api = '/finance-api/api/finance'

test('储蓄目标独立记录存取，同一账户的目标互不影响', async ({ page, browser }, testInfo) => {
  expect((await page.request.get(`${api}/savings-goals`)).status()).toBe(401)
  await page.goto('/login')
  await page.getByPlaceholder('请输入用户名').fill('live-user-1')
  await page.getByPlaceholder('请输入密码').fill('live-test-password')
  await page.getByRole('button', { name: '登录并继续' }).click()
  await expect(page).toHaveURL(/\/finance$/)
  const readAccount = async () => (await (await page.request.get(`${api}/accounts/2`)).json()).data
  const account = await readAccount()
  const initial = Number(account.currentBalance)
  await page.goto('/finance/more-features')
  await page.getByRole('link', { name: '储蓄目标', exact: true }).click()
  await expect(page.getByRole('heading', { name: '储蓄目标', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新增储蓄目标', exact: true }).click()
  await page.getByLabel('目标名称', { exact: true }).fill('应急金')
  await page.getByRole('button', { name: /关联现金账户/ }).click()
  await page.getByRole('option', { name: /测试储蓄/ }).click()
  await page.getByLabel(/目标金额/).fill('0')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('目标金额')
  await page.getByLabel(/目标金额/).fill('300')
  await page.getByLabel('截止日期（可选）').fill(`${new Date().getFullYear() + 1}-12-31`)
  await page.getByLabel('备注（可选）').fill('至少三个月生活费')
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeInViewport()
  const saved = page.waitForResponse(r => r.url().endsWith('/savings-goals') && r.request().method() === 'POST')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  const response = await saved
  expect(response.status()).toBe(200)
  const goal = (await response.json()).data
  const payload = response.request().postDataJSON()
  expect(payload.requestId).toBeTruthy()
  expect(Number(goal.currentAmount)).toBe(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const card = page.getByRole('article', { name: '应急金', exact: true })
  await expect(card).toContainText('还差 ¥300.00')
  await expect(card).toContainText('每月建议')
  await expect(page.getByRole('button', { name: '取出应急金', exact: true })).toBeDisabled()
  const replay = await page.request.post(`${api}/savings-goals`, { data: payload })
  expect((await replay.json()).data.id).toBe(goal.id)
  await page.getByRole('button', { name: '新增储蓄目标', exact: true }).click()
  await page.getByLabel('目标名称', { exact: true }).fill('买车基金')
  await page.getByRole('button', { name: /关联现金账户/ }).click()
  await expect(page.getByRole('option', { name: /测试储蓄/ })).toBeEnabled()
  await page.getByRole('option', { name: /测试储蓄/ }).click()
  await page.getByLabel(/目标金额/).fill('400')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const secondCard = page.getByRole('article', { name: '买车基金', exact: true })
  await expect(secondCard).toContainText('还差 ¥400.00')
  await expect(page.getByRole('article')).toHaveCount(2)
  const record = async (name: string, action: '存入' | '取出', amount: string) => {
    await page.getByRole('button', { name: `${action}${name}`, exact: true }).click()
    await page.getByLabel(`${action}金额（CNY）`, { exact: true }).fill(amount)
    const result = page.waitForResponse(r => r.url().endsWith('/entries') && r.request().method() === 'POST')
    await page.getByRole('button', { name: '确认记录', exact: true }).click()
    const response = await result
    expect(response.status()).toBe(200)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    return response
  }
  const deposit = await record('应急金', '存入', '300')
  const depositPayload = deposit.request().postDataJSON()
  expect(depositPayload.requestId).toBeTruthy()
  const repeat = await page.request.post(`${api}/savings-goals/${goal.id}/entries`, { data: depositPayload })
  expect((await repeat.json()).data.id).toBe((await deposit.json()).data.id)
  await expect(card).toContainText('已达到目标金额')
  await expect(secondCard).toContainText('还差 ¥400.00')
  await record('买车基金', '存入', '50')
  await expect(secondCard).toContainText('还差 ¥350.00')
  expect(Number((await readAccount()).currentBalance)).toBe(initial)
  await page.screenshot({ path: testInfo.outputPath('savings-independent-goals.png'), animations: 'disabled' })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  for (const action of ['存入应急金', '取出应急金', '应急金存取记录', '修改应急金', '删除应急金'])
    await expect(page.getByRole('button', { name: action, exact: true })).toBeInViewport()

  const foreignAccount = await page.request.post(`${api}/savings-goals`, { data: { ...payload, accountId: 3, requestId: randomUUID() } })
  expect(foreignAccount.status()).toBe(400)
  expect((await page.request.delete(`${api}/accounts/2`)).status()).toBe(400)
  for (const change of [{ currencyCode: 'USD' }, { status: 'archived' }]) {
    expect((await page.request.put(`${api}/accounts/2`, { data: { ...account, ...change } })).status()).toBe(400)
  }
  const other = await browser.newContext({ baseURL: 'http://127.0.0.1:4176' })
  try {
    expect((await other.request.post('/auth-api/api/auth/login', { data: { username: 'live-user-2', password: 'live-test-password' } })).status()).toBe(200)
    expect((await (await other.request.get(`${api}/savings-goals?userId=1`)).json()).data).toEqual([])
    expect((await other.request.put(`${api}/savings-goals/${goal.id}`, { data: { ...payload, accountId: 3 } })).status()).toBe(400)
    expect((await other.request.delete(`${api}/savings-goals/${goal.id}`)).status()).toBe(400)
    expect((await other.request.get(`${api}/savings-goals/${goal.id}/entries`)).status()).toBe(400)
    expect((await other.request.post(`${api}/savings-goals/${goal.id}/entries`, { data: depositPayload })).status()).toBe(400)
  } finally { await other.close() }
  const transfer = await page.request.post(`${api}/transactions`, { data: {
    userId: 1, type: 'transfer', fromAccountId: 1, toAccountId: 2, amount: 100,
    occurredAt: '2026-11-07T12:00:00', requestId: randomUUID(),
  } })
  expect(transfer.status()).toBe(200)
  const transaction = (await transfer.json()).data
  await page.getByRole('button', { name: '刷新储蓄目标', exact: true }).click()
  await expect(card).toContainText('已存 ¥300.00')
  await expect(secondCard).toContainText('已存 ¥50.00')
  expect((await page.request.delete(`${api}/transactions/${transaction.id}?userId=1`)).status()).toBe(200)
  await page.getByRole('button', { name: '已达成', exact: true }).click()
  await expect(card).toBeVisible()
  await record('应急金', '取出', '100')
  await expect(page.getByText('暂无已达成的目标')).toBeVisible()
  await page.getByRole('button', { name: '储蓄中', exact: true }).click()
  await expect(card).toContainText('已存 ¥200.00')
  await expect(secondCard).toContainText('已存 ¥50.00')
  expect((await page.request.post(`${api}/savings-goals/${goal.id}/entries`, {
    data: { ...depositPayload, type: 'withdrawal', amount: 201, requestId: randomUUID() },
  })).status()).toBe(400)
  await page.getByRole('button', { name: '取出应急金', exact: true }).click()
  await page.getByLabel('取出金额（CNY）').fill('201')
  await page.getByRole('button', { name: '确认记录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('不能超过该目标已存金额')
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '应急金存取记录', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('+¥300.00')
  await expect(page.getByRole('dialog')).toContainText('−¥100.00')
  await page.screenshot({ path: testInfo.outputPath('savings-history.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '修改应急金', exact: true }).click()
  await page.getByLabel('目标名称', { exact: true }).fill('旅行基金')
  await page.getByLabel('截止日期（可选）').fill('')
  await page.getByLabel('备注（可选）').fill('')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('article', { name: '旅行基金' })).toContainText('已存 ¥200.00')
  await page.getByRole('button', { name: '删除旅行基金', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('及其全部存取记录')
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(secondCard).toContainText('已存 ¥50.00')
  expect((await page.request.delete(`${api}/accounts/2`)).status()).toBe(400)
  await page.getByRole('button', { name: '删除买车基金', exact: true }).click()
  await page.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(page.getByText('暂无储蓄目标', { exact: true })).toBeVisible()
  expect(Number((await readAccount()).currentBalance)).toBe(initial)
})
