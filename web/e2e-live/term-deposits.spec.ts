import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

const api = '/finance-api/api/finance'
test('定期存单贯通账户资产、目标预留、到期提醒、续存和撤销', async ({ page, browser }, testInfo) => {
  test.setTimeout(90_000)
  expect((await page.request.get(`${api}/term-deposits`)).status()).toBe(401)
  await page.goto('/login')
  await page.getByPlaceholder('请输入用户名').fill('live-user-1')
  await page.getByPlaceholder('请输入密码').fill('live-test-password')
  await page.getByRole('button', { name: '登录并继续' }).click()
  await expect(page).toHaveURL(/\/finance$/)
  const today = new Intl.DateTimeFormat('sv-SE', { timeZone: 'Asia/Shanghai' }).format(new Date())
  const start = `${Number(today.slice(0, 4)) - 1}${today.slice(4)}`
  const cash = (await (await page.request.post(`${api}/accounts`, { data: { userId: 1, accountTypeId: 1, name: '存单专用现金', currentBalance: 1000, includeInNetWorth: true } })).json()).data
  const goal = (await (await page.request.post(`${api}/savings-goals`, { data: { name: '定期预留目标', accountId: cash.id, targetAmount: 1000, requestId: randomUUID() } })).json()).data
  expect((await page.request.post(`${api}/savings-goals/${goal.id}/entries`, { data: { type: 'deposit', amount: 500, occurredOn: today, requestId: randomUUID() } })).status()).toBe(200)
  const balance = async (id: number) => Number((await (await page.request.get(`${api}/accounts/${id}`)).json()).data.currentBalance)
  const assets = async () => Number((await (await page.request.get(`${api}/accounts/overview?userId=1`)).json()).data.totalAssets)
  const initialAssets = await assets()
  const choose = async (label: string, name: RegExp) => {
    await page.getByRole('button', { name: new RegExp(`^${label} `) }).click()
    await page.getByRole('listbox', { name: label, exact: true }).getByRole('option', { name }).click()
  }
  const submit = async (button: string, endpoint: string, expected = 200) => {
    const pending = page.waitForResponse(r => r.url().endsWith(endpoint) && r.request().method() === 'POST')
    await page.getByRole('button', { name: button, exact: true }).click()
    const response = await pending
    expect(response.status(), await response.text()).toBe(expected)
    return response
  }
  await page.goto('/finance/more-features')
  await page.getByRole('link', { name: '定期存款', exact: true }).click()
  await page.getByRole('button', { name: '新增存单', exact: true }).first().click()
  await page.getByLabel('存单名称', { exact: true }).fill('一年存单')
  await page.getByRole('button', { name: '＋ 新增定期账户', exact: true }).click()
  await page.getByLabel('账户名称', { exact: true }).fill('测试定期银行')
  await submit('创建账户', '/accounts')
  await choose('转出现金账户', /存单专用现金/)
  await page.getByLabel('本金（CNY）', { exact: true }).fill('800')
  await page.getByLabel('年利率（%）', { exact: true }).fill('2')
  await page.getByLabel('起息日', { exact: true }).fill(start)
  await page.getByLabel('到期日', { exact: true }).fill(today)
  await choose('默认到账账户', /存单专用现金/)
  await submit('保存', '/term-deposits', 400)
  await expect(page.getByRole('alert')).toContainText('释放 300.00')
  await page.getByRole('button', { name: '添加扣减储蓄目标', exact: true }).click()
  await page.getByLabel('扣减储蓄目标金额 1', { exact: true }).fill('300')
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(page.getByRole('button', { name: '保存', exact: true })).toBeInViewport()
  expect(await page.locator('.common-modal-body').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await expect(page.getByRole('heading', { name: '新增存单', exact: true })).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('term-form.png'), animations: 'disabled' })
  const response = await submit('保存', '/term-deposits')
  const d = (await response.json()).data
  const payload = response.request().postDataJSON()
  expect((await (await page.request.post(`${api}/term-deposits`, { data: payload })).json()).data.id).toBe(d.id)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await balance(cash.id)).toBe(200)
  expect(await balance(d.accountId)).toBe(800)
  expect(await assets()).toBe(initialAssets)
  const card = page.getByRole('article', { name: '一年存单', exact: true })
  await expect(card).toContainText('预计利息 ¥16.00')
  for (const name of ['支取或续存一年存单', '一年存单详情', '修改一年存单', '撤销一年存单']) await expect(page.getByRole('button', { name, exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await page.request.delete(`${api}/accounts/${d.accountId}`)).status()).toBe(400)
  const termAccount = (await (await page.request.get(`${api}/accounts/${d.accountId}`)).json()).data
  for (const change of [{ status: 'archived' }, { currencyCode: 'USD' }, { accountTypeId: 1 }])
    expect((await page.request.put(`${api}/accounts/${d.accountId}`, { data: { ...termAccount, ...change } })).status()).toBe(400)
  // Direct balance edits cannot change derived principal.
  expect((await page.request.put(`${api}/accounts/${d.accountId}`, { data: { ...termAccount, currentBalance: 9999 } })).status()).toBe(200)
  expect(await balance(d.accountId)).toBe(800)
  const other = await browser.newContext({ baseURL: 'http://127.0.0.1:4176' })
  try {
    await other.request.post('/auth-api/api/auth/login', { data: { username: 'live-user-2', password: 'live-test-password' } })
    expect((await other.request.get(`${api}/term-deposits/${d.id}`)).status()).toBe(400)
    expect((await other.request.post(`${api}/term-deposits/${d.id}/cancel`, { data: { requestId: randomUUID() } })).status()).toBe(400)
  } finally { await other.close() }
  await page.goto('/profile/reminders')
  await page.getByRole('button', { name: /一年存单.*查看详情/ }).click()
  await expect(page).toHaveURL(new RegExp(`term-deposits\\?reminderId=${d.id}`))
  await expect(page.getByRole('dialog')).toContainText('预计本息 ¥816.00')
  await page.getByRole('button', { name: '关闭', exact: true }).last().click()
  await page.getByRole('button', { name: '支取或续存一年存单', exact: true }).click()
  await choose('处理方式', /本息续存/)
  await page.getByLabel('实际利息（CNY）', { exact: true }).fill('15.5')
  await page.getByLabel('新年利率（%）', { exact: true }).fill('1.8')
  await page.screenshot({ path: testInfo.outputPath('term-renewal.png'), animations: 'disabled' })
  await submit('确认结算', `/term-deposits/${d.id}/settle`)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await balance(cash.id)).toBe(200)
  expect(await balance(d.accountId)).toBe(815.5)
  expect(await assets()).toBe(initialAssets + 15.5)
  await page.goto('/finance/transactions')
  await page.getByRole('searchbox', { name: '搜索流水名称或备注' }).fill('一年存单')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(page.locator('.transaction-row')).toHaveCount(1)
  await expect(page.locator('.transaction-row .transaction-actions')).toHaveCount(0)
  await expect(page.getByRole('link', { name: '定期利息 · 一年存单', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '定期利息 · 一年存单', exact: true }).click()
  await expect(page).toHaveURL(/term-deposits$/)
  const detail = (await (await page.request.get(`${api}/term-deposits/${d.id}`)).json()).data
  const renewal = detail.operations.find((o: { operation: string }) => o.operation === 'renew_all')
  await page.getByRole('button', { name: '已结清', exact: true }).click()
  await page.getByRole('button', { name: '一年存单详情', exact: true }).click()
  await page.getByRole('button', { name: '撤销结算', exact: true }).click()
  await submit('确认撤销', `/term-deposits/${d.id}/reverse`)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await balance(d.accountId)).toBe(800)
  expect(await assets()).toBe(initialAssets)
  expect((await (await page.request.get(`${api}/term-deposits/${renewal.childDepositId}`)).json()).data.deposit.status).toBe('voided')
  await page.getByRole('button', { name: '全部', exact: true }).click()
  await page.getByRole('button', { name: '支取或续存一年存单', exact: true }).click()
  await submit('确认结算', `/term-deposits/${d.id}/settle`)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await balance(cash.id)).toBe(1016)
  expect(await balance(d.accountId)).toBe(0)
  await page.getByRole('button', { name: '一年存单详情', exact: true }).click()
  await page.getByRole('button', { name: '撤销结算', exact: true }).click()
  await submit('确认撤销', `/term-deposits/${d.id}/reverse`)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '撤销一年存单', exact: true }).click()
  await submit('确认撤销', `/term-deposits/${d.id}/cancel`)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  expect(await balance(cash.id)).toBe(1000)
  const savedGoal = (await (await page.request.get(`${api}/savings-goals`)).json()).data.find((g: { id: number }) => g.id === goal.id)
  expect(Number(savedGoal.currentAmount)).toBe(500)
  // Populate enough backfilled certificates to verify only the list scrolls.
  for (let i = 0; i < 10; i++) expect((await page.request.post(`${api}/term-deposits`, { data: { ...payload, name: `历史存单 ${i}`, openingMode: 'existing', fundingAccountId: null, savingsAllocations: [], requestId: randomUUID() } })).status()).toBe(200)
  await page.getByRole('button', { name: '刷新存单', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(10)
  const header = await page.getByRole('heading', { name: '定期存款', exact: true }).boundingBox()
  await page.locator('.term-list').evaluate(el => { el.scrollTop = el.scrollHeight })
  expect((await page.getByRole('heading', { name: '定期存款', exact: true }).boundingBox())?.y).toBe(header?.y)
  expect(await page.locator('.page-content').evaluate(el => el.scrollTop)).toBe(0)
  expect(await page.locator('.term-list').evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  await page.screenshot({ path: testInfo.outputPath('term-list.png'), animations: 'disabled' })
})
